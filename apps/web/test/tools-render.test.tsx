import { NextIntlClientProvider } from "next-intl";
import type { ReactNode } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { describe, expect, it } from "vitest";
import enCore from "../messages/en.json" with { type: "json" };
import enTools from "../messages/en/tools.json" with { type: "json" };
import hiCore from "../messages/hi.json" with { type: "json" };
import hiTools from "../messages/hi/tools.json" with { type: "json" };
import { KundliResult } from "../src/components/tools/KundliResult";
import { MatchResult } from "../src/components/tools/MatchResult";
import {
  DashaResult,
  MangalResult,
  NumberResult,
  SadeSatiResult,
  SunMoonAscendant,
} from "../src/components/tools/Results";
import type { Dasha, Doshas, Kundli, Match, Numerology } from "../src/lib/tools/types";
// Generated by calling the engine (see _comment inside); never hand-typed.
import fx from "./tools.fixtures.json" with { type: "json" };

const kundli = fx.kundli as unknown as Kundli;
const unknown = fx.kundliUnknown as unknown as Kundli;
const dasha = fx.dasha as unknown as Dasha;
const doshas = fx.doshas as unknown as Doshas;
const match = fx.match as unknown as Match;
const numerology = fx.numerology as unknown as Numerology;
const birth = {
  date: "2000-01-01",
  time: "12:00",
  place: { lat: 28.6139, lon: 77.209, tz: "Asia/Kolkata" },
};

function render(node: ReactNode, locale: "en" | "hi" = "en") {
  const messages = locale === "en" ? { ...enCore, ...enTools } : { ...hiCore, ...hiTools };
  return renderToStaticMarkup(
    <NextIntlClientProvider locale={locale} messages={messages} timeZone="Asia/Kolkata">
      {node}
    </NextIntlClientProvider>,
  );
}

describe("result renderers on engine output", () => {
  it("kundli shows every graha, the ascendant and the save button", () => {
    const html = render(
      <KundliResult
        kundli={kundli}
        dasha={{ ok: true, data: dasha }}
        doshas={{ ok: true, data: doshas }}
        birth={birth}
      />,
    );
    for (const g of kundli.grahas)
      expect(html).toContain(enTools.toolAstro.graha[g.id as keyof typeof enTools.toolAstro.graha]);
    expect(html).toContain("Ascendant (lagna)");
    expect(html).toContain(
      kundli.ascendant!.dms_in_sign.replace(/"/g, "&quot;").replace(/'/g, "&#x27;"),
    );
    expect(html).toContain("Save my kundli");
    expect(html).not.toMatch(/#[0-9a-f]{6}/i);
  });

  it("kundli shows the gated message when doshas await review", () => {
    const html = render(
      <KundliResult
        kundli={kundli}
        dasha={{ ok: true, data: dasha }}
        doshas={{ ok: false, code: "tables_not_reviewed" }}
        birth={birth}
      />,
    );
    expect(html).toContain(enTools.toolsUi.errors.tables_not_reviewed);
  });

  it("unknown birth time: no ascendant, explanation shown", () => {
    const html = render(<SunMoonAscendant kundli={unknown} />);
    expect(html).toContain(enTools.toolsUi.result.unknownAscendant);
  });

  it("dasha lists nine mahadashas and the current period", () => {
    const html = render(<DashaResult dasha={dasha} tz="Asia/Kolkata" />);
    expect((html.match(/<tr/g) ?? []).length).toBe(10);
    expect(html).toContain(
      enTools.toolAstro.graha[dasha.current!.mahadasha as keyof typeof enTools.toolAstro.graha],
    );
  });

  it("doshas show the engine's rule text and the review notice", () => {
    const html = render(
      <MangalResult mangal={doshas.mangal} reviewStatus={doshas.tables_review_status} />,
    );
    expect(html).toContain(doshas.mangal.rule);
    expect(html).toContain(enTools.toolsUi.result.pendingReview);
    const ss = render(
      <SadeSatiResult ss={doshas.sade_sati} tz="Asia/Kolkata" reviewStatus="verified" />,
    );
    expect(ss).not.toContain(enTools.toolsUi.result.pendingReview);
  });

  it("numerology shows the engine's steps and letters", () => {
    const html = render(<NumberResult kind="bhagyank" numerology={numerology} />);
    expect(html).toContain(numerology.bhagyank!.steps);
    const name = render(<NumberResult kind="name_number" numerology={numerology} />);
    expect(name).toContain(
      `${numerology.name_number!.letters[0]!.letter} = ${numerology.name_number!.letters[0]!.value}`,
    );
  });

  it("matching shows all eight kootas and the total, in both locales", () => {
    for (const locale of ["en", "hi"] as const) {
      const html = render(<MatchResult match={match} />, locale);
      for (const k of match.kootas) expect(html).toContain(`${k.points} / ${k.max}`);
      expect(html).toContain(String(match.total));
    }
    expect(render(<MatchResult match={match} />, "hi")).toContain("कूट");
  });
});
