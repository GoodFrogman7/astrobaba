// Generates the RenderData fixtures for the printable report pages (docs/api/revenue.md §2.3)
// by calling the running astro engine. Never hand-edit the output; re-run this script instead.
//
//   ASTRO_URL=http://localhost:8001 node scripts/report-fixtures.mjs
//
// The two births are fictional samples. Places come from the engine's own city index, and every
// astro value comes from the engine's responses, exactly as the reports backend snapshots them.
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ASTRO = (process.env.ASTRO_URL ?? "http://localhost:8001").replace(/\/$/, "");
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "test", "fixtures", "report");
// Fixed "purchase" instant so the dasha and Sade Sati "as of" values never drift.
const CREATED_AT = "2026-10-21T08:30:00Z";
const AS_OF = CREATED_AT.slice(0, 10);

const SAMPLES = {
  a: { label: "Asha Verma", date: "1990-08-15", time: "06:30", city: "New Delhi" },
  b: { label: "Rohan Mehta", date: "1988-11-03", time: "21:45", city: "Mumbai" },
};

async function call(method, path, body) {
  const res = await fetch(ASTRO + path, {
    method,
    headers: { "content-type": "application/json" },
    body: body ? JSON.stringify(body) : undefined,
  });
  if (!res.ok) throw new Error(`${method} ${path}: ${res.status} ${await res.text()}`);
  return res.json();
}

async function place(city) {
  const q = new URLSearchParams({ q: city, limit: "1", country: "IN" });
  const found = (await call("GET", `/v1/cities?${q}`)).results[0];
  if (!found) throw new Error(`city not found: ${city}`);
  return { name: found.label, lat: found.lat, lon: found.lon, tz: found.tz };
}

/** One snapshot entry: the engine outputs for a saved kundli. */
async function entry(sample, { time = sample.time } = {}) {
  const p = await place(sample.city);
  const birth = { date: sample.date, time, place: p };
  const engineBirth = { date: sample.date, time, place: { lat: p.lat, lon: p.lon, tz: p.tz } };
  const q = new URLSearchParams({
    lat: String(p.lat),
    lon: String(p.lon),
    tz: p.tz,
    date: sample.date,
  });
  return {
    label: sample.label,
    birth,
    engineBirth,
    kundli: await call("POST", "/v1/kundli", { birth: engineBirth }),
    dasha: await call("POST", "/v1/dasha", { birth: engineBirth, as_of: AS_OF }),
    doshas: await call("POST", "/v1/doshas", { birth: engineBirth, as_of: AS_OF }),
    numerology: await call("POST", "/v1/numerology", {
      name: sample.label,
      date_of_birth: sample.date,
    }),
    panchang: await call("GET", `/v1/panchang?${q}`),
  };
}

function strip(entry) {
  const rest = { ...entry };
  delete rest.engineBirth;
  return rest;
}

function renderData(id, sku, language, meta, kundlis, match = null) {
  return {
    _comment:
      "Generated by apps/web/scripts/report-fixtures.mjs from the astro engine; never hand-edited.",
    report: { id, sku, language, created_at: CREATED_AT, engine_version: meta.version },
    snapshot: { kundlis, match, meta },
  };
}

async function main() {
  const meta = await call("GET", "/v1/meta");
  const a = await entry(SAMPLES.a);
  const b = await entry(SAMPLES.b);
  const bNoTime = await entry(SAMPLES.b, { time: null });
  // Traditional Ashtakoota roles: partner 1 is read as the groom, partner 2 as the bride.
  const match = await call("POST", "/v1/match", { groom: b.engineBirth, bride: a.engineBirth });

  const files = {
    "fixture-kundli-en": renderData("fixture-kundli-en", "kundli_report", "en", meta, [strip(a)]),
    "fixture-kundli-hi": renderData("fixture-kundli-hi", "kundli_report", "hi", meta, [strip(a)]),
    "fixture-kundli-notime-en": renderData(
      "fixture-kundli-notime-en",
      "kundli_report",
      "en",
      meta,
      [strip(bNoTime)],
    ),
    "fixture-matching-en": renderData(
      "fixture-matching-en",
      "matching_report",
      "en",
      meta,
      [strip(b), strip(a)],
      match,
    ),
    "fixture-matching-hi": renderData(
      "fixture-matching-hi",
      "matching_report",
      "hi",
      meta,
      [strip(b), strip(a)],
      match,
    ),
  };

  // Format like the rest of the repo so `prettier --check` passes without a second step.
  const prettier = await import("prettier");
  await mkdir(OUT, { recursive: true });
  for (const [name, data] of Object.entries(files)) {
    const file = join(OUT, `${name}.json`);
    const config = (await prettier.resolveConfig(file)) ?? {};
    const text = await prettier.format(JSON.stringify(data), { ...config, parser: "json" });
    await writeFile(file, text);
    console.log(`wrote ${file}`);
  }
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
