def slugify(name: str) -> str:
    ascii_name = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", ascii_name.lower()).strip("-")


def main() -> int:
    index = CityIndex(ROOT / "build" / "cities.tsv.gz")
    alt_names: dict[int, list[str]] = {}
    with gzip.open(ROOT / "build" / "cities.tsv.gz", "rt", encoding="utf-8", newline="") as f:
        f.readline()
        for row in csv.DictReader(f, delimiter="\t", quoting=csv.QUOTE_NONE, escapechar="\\"):
            alt_names[int(row["id"])] = [a for a in row["alt"].split("|") if a]

    out, missing = [], []
    for name, name_hi in CITIES.items():
        exact = [c for c in index.search(name, 25, "IN") if normalize(c.name) == normalize(name)]
        matches = exact or index.search(name, 1, "IN")
        if not matches:
            missing.append(name)
            continue
        city = max(matches, key=lambda c: c.population)
        deva = [a for a in alt_names.get(city.id, []) if any("ऀ" <= ch <= "ॿ" for ch in a)]
        out.append(
            {
                "slug": slugify(name),
                "geonameid": city.id,
                "name_en": name,
                "name_hi": name_hi,
                "geonames_hi": deva[0] if deva else None,
                "lat": city.lat,
                "lon": city.lon,
                "tz": city.tz,
                "population": city.population,
            }
        )
    if missing:
        print(f"not found in the city index: {missing}", file=sys.stderr)
        return 1
    slugs = [c["slug"] for c in out]
    if len(set(slugs)) != len(slugs) or len({c["geonameid"] for c in out}) != len(out):
        print("duplicate slug or geonameid", file=sys.stderr)
        return 1
    out.sort(key=lambda c: -c["population"])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        json.dumps(
            {
                "source": "Places: GeoNames (https://www.geonames.org), CC-BY 4.0, via "
                "data/build/cities.tsv.gz. name_hi: curated standard spelling (geonames_hi keeps "
                "GeoNames' first Devanagari alternate). Generated by data/build_seo_cities.py; "
                "do not edit by hand.",
                "cities": out,
            },
            ensure_ascii=False,
            indent=1,
        )
        + "\n",
        encoding="utf-8",
    )
    print(f"wrote {len(out)} cities to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
