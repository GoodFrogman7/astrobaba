"""Build data/seo/cities.json: Indian cities that get their own panchang pages.

Coordinates, time zones, ids and Hindi names come from the engine's GeoNames index
(data/build/cities.tsv.gz, CC-BY 4.0); only the English names below are curated. GeoNames ids
are the same in the bundled extract and the full dump, so the output is stable.

Usage: uv run python data/build_seo_cities.py
"""

